@transaction.atomic
def seed_questionnaire(version=1):
    created_questions = 0
    for order, item in enumerate(QUESTIONNAIRE, start=1):
        question, created = Questions.objects.get_or_create(
            slot=item['slot'],
            version=version,
            defaults={'text': item['text'], 'order': order, 'is_active': True},
        )
        if not created:
            continue

        created_questions += 1
        Choice.objects.bulk_create([
            Choice(question=question, text=text, value=value, outcome=outcome, order=position)
            for position, (text, value, outcome) in enumerate(item['choices'], start=1)
        ])

    return created_questions
